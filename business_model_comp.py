def run_scenario(label, price_change=0, sales_change=0, cost_change=0):
    new_gross_revenue = sum(
        p["price"] * (1 + price_change) * p["units"] * (1 + sales_change) for p in products
    )
    new_sales_tax_remitted = (
        new_gross_revenue * sales_tax_rate / (1 + sales_tax_rate) if sales_tax_rate > 0 else 0
    )
    new_revenue = new_gross_revenue - new_sales_tax_remitted

    new_base_variable_costs = sum(
        p["var_cost"] * (1 + cost_change) * p["units"] * (1 + sales_change) for p in products
    )
    new_waste_cost = new_base_variable_costs * waste_rate
    new_variable_costs = new_base_variable_costs + new_waste_cost

    new_pos_fees = new_revenue * pos_fee_rate

    new_total_costs = fixed_costs + new_variable_costs + employee_costs + new_pos_fees + supplier_costs
    new_profit = new_revenue - new_total_costs

    print(f"\n--- Scenario: {label} ---")
    print(f"Revenue:       {currency(new_revenue)}")
    print(f"Total Costs:   {currency(new_total_costs)}")
    print(f"Profit / Loss: {currency(new_profit)}")

    return {"revenue": new_revenue, "total_costs": new_total_costs, "profit": new_profit}


def recalculate_all_scenarios():
    price_up = run_scenario("All prices +10%", price_change=0.10)
    sales_down = run_scenario("Sales -20%", sales_change=-0.20)
    cost_up = run_scenario("Ingredient/product costs +15%", cost_change=0.15)
    return price_up, sales_down, cost_up


