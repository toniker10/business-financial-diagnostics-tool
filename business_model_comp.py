def get_float(prompt, min_value=None, example=None):
    if example:
        print(f"   Example: {example}")
    while True:
        try:
            raw = input(prompt).strip().replace("€", "").replace("$", "").replace(",", "")
            value = float(raw)
            if min_value is not None and value < min_value:
                print(f"   ⚠️  Please enter a number of at least {min_value}. Try again.")
                continue
            return value
        except ValueError:
            print("   ⚠️  That's not a valid number. Please type digits only, e.g. 3.50")


def get_int(prompt, min_value=0, example=None):
    if example:
        print(f"   Example: {example}")
    while True:
        try:
            raw = input(prompt).strip().replace(",", "")
            value = int(raw)
            if value < min_value:
                print(f"   ⚠️  Please enter a whole number of at least {min_value}. Try again.")
                continue
            return value
        except ValueError:
            print("   ⚠️  That's not a valid whole number. Please type digits only, e.g. 300")


def get_yes_no(prompt):
    while True:
        answer = input(prompt + " (type y for yes or n for no): ").strip().lower()
        if answer in ("y", "yes"):
            return True
        if answer in ("n", "no"):
            return False
        print("   ⚠️  Please type 'y' or 'n'.")


